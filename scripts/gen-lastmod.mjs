#!/usr/bin/env node
/**
 * Writes src/data/lastmod.json: real "last changed" dates from git, used for sitemap <lastmod>, JSON-LD dateModified and the
 * dataset page. Never uses build time.
 *  - rows:  per cartridge row ("brandSlug/modelSlug"), the date of the last commit that changed that row's JSON in src/data/filters.json
 *  - files: last commit date of each content source file (pages/guides code)
 *  - first: first commit date of selected files (for datePublished)
 * Rows/files with uncommitted changes get today's date (it will be their commit date).
 * In a shallow clone (history missing) the committed lastmod.json is left untouched, so deploys cannot flatten every date.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
const root = fileURLToPath(new URL('..', import.meta.url));
const out = join(root, 'src/data/lastmod.json');
const git = (...a) => execFileSync('git', a, { cwd: root, encoding: 'utf8', maxBuffer: 1 << 28 }).trim();
try {
  if (git('rev-parse', '--is-shallow-repository') === 'true') { console.log('gen-lastmod: shallow clone, keeping committed src/data/lastmod.json'); process.exit(0); }
} catch { console.log('gen-lastmod: not a git checkout, keeping committed src/data/lastmod.json'); process.exit(0); }

const today = (() => { const d = new Date(); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`; })();
const FILE = 'src/data/filters.json';
const hash = (o) => createHash('sha1').update(JSON.stringify(o)).digest('hex');
const rowsOf = (txt) => new Map(JSON.parse(txt).filters.map((f) => [`${f.brandSlug}/${f.modelSlug}`, hash(f)]));

// ---- rows ----
const commits = git('log', '--reverse', '--format=%H %cs', '--', FILE).split('\n').filter(Boolean).map((l) => l.split(' '));
const rows = {}; let prev = new Map();
for (const [sha, date] of commits) {
  const cur = rowsOf(git('show', `${sha}:${FILE}`));
  for (const [k, h] of cur) if (prev.get(k) !== h) rows[k] = date;
  prev = cur;
}
const head = prev;
const dirty = git('status', '--porcelain').split('\n').filter(Boolean).map((l) => l.slice(3).replace(/^"|"$/g, ''));
if (dirty.includes(FILE)) for (const [k, h] of rowsOf(readFileSync(join(root, FILE), 'utf8'))) if (head.get(k) !== h) rows[k] = today;
for (const k of Object.keys(rows)) if (!head.has(k) && !dirty.includes(FILE)) delete rows[k];

// ---- files ----
const tracked = ['src/pages/index.astro', 'src/pages/about.astro', 'src/pages/contact.astro', 'src/pages/guide.astro', 'src/pages/size/index.astro', 'src/pages/supplies/index.astro',
  'src/pages/guides/index.astro', 'src/pages/data/index.astro', 'src/pages/affiliate-disclosure.astro', 'src/pages/disclaimer.astro', 'src/pages/privacy.astro', 'src/pages/terms.astro',
  'src/lib/brandcopy.ts', 'src/lib/guides.ts', 'src/lib/guides2.ts',
  'src/pages/tools/index.astro', 'src/pages/tools/cross-reference.astro', 'src/pages/tools/filter-schedule.astro',
  'src/lib/xref.mjs', 'src/lib/care-calc.mjs'];
const files = {}, first = {};
for (const f of tracked) {
  const p = join(root, f);
  if (!existsSync(p)) continue;
  const d = git('log', '-1', '--format=%cs', '--', f);
  files[f] = dirty.some((x) => x === f || f.startsWith(x)) || !d ? today : d;
  const fc = git('log', '--diff-filter=A', '--format=%cs', '--', f).split('\n').filter(Boolean).pop();
  first[f] = fc || today;
}
first[FILE] = commits.length ? commits[0][1] : today;
const next = JSON.stringify({ note: 'Generated by scripts/gen-lastmod.mjs from git history. Do not edit by hand.', rows, files, first }, null, 1) + '\n';
if (!existsSync(out) || readFileSync(out, 'utf8') !== next) writeFileSync(out, next);
console.log(`gen-lastmod: ${Object.keys(rows).length} rows, ${Object.keys(files).length} files`);
